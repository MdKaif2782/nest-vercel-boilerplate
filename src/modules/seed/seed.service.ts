  private async seedAdvanceRecords(employees: any[], adminId: string) {
    const advances = [];

    // Only create advance records for employees that have an advance balance
    for (const emp of employees) {
      if (emp.advanceBalance > 0) {
        const advance = await this.prisma.employeeAdvance.create({
          data: {
            employeeId: emp.id,
            amount: emp.advanceBalance,
            type: 'GIVEN',
            description: `Initial advance for ${emp.name}`,
            paymentMethod: 'CASH',
            balanceAfter: emp.advanceBalance,
          },
        });
        advances.push(advance);

        // Also create auto-generated expense for the advance
        await this.prisma.expense.create({
          data: {
            title: `Employee Advance - ${emp.name}`,
            description: `Advance payment to ${emp.name} (${emp.employeeId})`,
            amount: emp.advanceBalance,
            category: 'EMPLOYEE_ADVANCE',
            expenseDate: new Date(),
            paymentMethod: 'CASH',
            status: 'APPROVED',
            isAutoGenerated: true,
            employeeAdvanceId: advance.id,
            recordedBy: adminId,
          },
        });
      }
    }

    this.logger.log(`${advances.length} advance records created`);
    return advances;
  }

