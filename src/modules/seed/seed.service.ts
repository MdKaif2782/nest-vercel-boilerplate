  //  SEED: SALARY RECORDS
  // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  private async seedSalaryRecords(employees: any[]) {
    const salaries = [];
    const currentDate = new Date();
    const currentMonth = currentDate.getMonth() + 1; // 1-12
    const currentYear = currentDate.getFullYear();

    // Previous month for paid salaries
    const prevMonth = currentMonth === 1 ? 12 : currentMonth - 1;
    const prevYear = currentMonth === 1 ? currentYear - 1 : currentYear;

    for (const emp of employees) {
      const allowances =
        emp.homeRentAllowance +
        emp.healthAllowance +
        emp.travelAllowance +
        emp.mobileAllowance +
        emp.otherAllowances;

      const grossSalary = emp.baseSalary + allowances;

      // Create a PAID salary for previous month
      const paidSalary = await this.prisma.salary.create({
        data: {
          employeeId: emp.id,
          month: prevMonth,
          year: prevYear,
          baseSalary: emp.baseSalary,
          allowances,
          overtimeHours: 5,
          overtimeAmount: (emp.overtimeRate || 0) * 5,
          bonus: 0,
          deductions: 0,
          advanceDeduction: 0,
          grossSalary,
          netSalary: grossSalary + (emp.overtimeRate || 0) * 5,
          status: 'PAID',
          paidDate: new Date(prevYear, prevMonth - 1, 28),
          paymentMethod: 'BANK_TRANSFER',
          reference: `SAL-${prevMonth}-${prevYear}-${emp.employeeId}`,
          notes: 'Seeded paid salary',
        },
      });
      salaries.push(paidSalary);

      // Create a PENDING salary for current month
      const pendingSalary = await this.prisma.salary.create({
        data: {
          employeeId: emp.id,
          month: currentMonth,
          year: currentYear,
          baseSalary: emp.baseSalary,
          allowances,
          overtimeHours: 0,
          overtimeAmount: 0,
          bonus: 0,
          deductions: 0,
          advanceDeduction: 0,
          grossSalary,
          netSalary: grossSalary,
          status: 'PENDING',
          notes: 'Seeded pending salary - ready to be paid',
        },
      });
      salaries.push(pendingSalary);
    }

    this.logger.log(`${salaries.length} salary records created`);
    return salaries;
  }

